  const searching = query.trim().length > 0;

  const fixes = useMemo(() => TROUBLESHOOTING.filter((t) => matches(query, t.problem, t.fix)), [query]);
  const faqs = useMemo(() => FAQS.filter((f) => matches(query, f.q, f.a)), [query]);
